function inside(x: number, y: number, points: Point[]) {
  let hit = false;
  for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
    const [ax, ay] = points[i], [bx, by] = points[j];
    if ((ay > y) !== (by > y) && x < (bx - ax) * (y - ay) / (by - ay) + ax) hit = !hit;
  }
  return hit;
}

export function generateTerrain(mask: Uint8Array, cols: number, cell: number, map: TerrainId, seed: number) {
  const layout = layouts[map];
  for (let i = 0; i < mask.length; i++) {
    const x = (i % cols) * cell;
    const y = Math.floor(i / cols) * cell;
    const dx = Math.sin(y / 37 + seed) * 5 + Math.sin(y / 13) * 2;
    const dy = Math.sin(x / 47 + seed) * 6 + Math.sin(x / 17) * 3;
    mask[i] = layout.land.some(p => inside(x + dx, y + dy, p)) &&
      !layout.holes.some(p => inside(x + dx, y + dy, p)) ? 1 : 0;
  }
}
